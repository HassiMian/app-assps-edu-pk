'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { resolveAuthenticatedAttendanceMarker } = require('./attendanceMarkerIdentity')

test('positive integer auth user is the marker', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:42}),42))
test('positive digit-string auth user is the marker', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:'42'}),42))
test('student id cannot replace authenticated actor', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:42, student_id:99}),42))
test('client marker property ignored', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:42, marked_by:99}),42))
test('missing identity refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({}),null))
test('null user refused', () => assert.equal(resolveAuthenticatedAttendanceMarker(null),null))
test('null ID refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:null}),null))
test('zero user refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:0}),null))
test('negative user refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:-5}),null))
test('float user refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:1.5}),null))
test('negative string refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:'-3'}),null))
test('zero string refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:'0'}),null))
test('whitespace string refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:' 7'}),null))
test('exponential string refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:'1e3'}),null))
test('leading-zero string refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:'007'}),null))
test('infinity refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:Infinity}),null))
test('big integer refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:Number.MAX_SAFE_INTEGER+1}),null))
test('boolean refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:true}),null))
test('array refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:[42]}),null))
test('object refused', () => assert.equal(resolveAuthenticatedAttendanceMarker({id:{toString:()=>42}}),null))
test('route does not read marked_by from body for bulk attendance',()=>{
 const source=readFileSync(require.resolve('./attendanceRoutes.js'),'utf8')
 const start=source.indexOf("router.post('/mark',")
 const end=source.indexOf("router.post('/mark-by-gr',",start)
 const block=source.slice(start,end)
 assert.match(block,/resolveAuthenticatedAttendanceMarker\(req\.user\)/)
 assert.doesNotMatch(block,/const \{ records, marked_by \} = req\.body/)
})
test('route rejects missing authenticated marker with 403 after rollback',()=>{
 const source=readFileSync(require.resolve('./attendanceRoutes.js'),'utf8')
 assert.match(source,/if \(markedByUserId === null\) \{\s*await client\.query\('ROLLBACK'\)/)
 assert.match(source,/ATTENDANCE_MARKER_NOT_AUTHENTICATED/)
})
