'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const migration=fs.readFileSync(path.join(__dirname,'../../../ops/release/class8-promotion/011_class_eight_result_six_scored_subjects_20261030.sql'),'utf8')
test('explicit owner-directed Quran Nazra skip affects only grade Eight results, never fabricates scores',()=>{
 assert.match(migration,/subject='Quran \/ Nazra' AND is_active=true/)
 assert.match(migration,/UPDATE exam_subjects SET is_active=false/)
 assert.match(migration,/WHERE school_id=1 AND id=74 AND exam_id=9/)
 assert.match(migration,/expected_subject_count=6/)
 assert.match(migration,/COUNT\(DISTINCT r.student_id\)=11/)
 assert.match(migration,/COUNT\(DISTINCT r.total_marks\)=1/)
 assert.match(migration,/approval_status='pending'/)
 assert.match(migration,/print_verified_at IS NULL AND academic_approved_at IS NULL/)
 assert.doesNotMatch(migration,/UPDATE\s+exam_results\s+SET/i)
 assert.doesNotMatch(migration,/approval_status='approved'/i)
 assert.doesNotMatch(migration,/DISABLE TRIGGER/i)
})
