'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const src=fs.readFileSync(path.join(__dirname,'../services/whatsapp/jarvisCognitiveTools.js'),'utf8')
const start=src.indexOf('async function enterExamMarks(')
const end=src.indexOf('async function getOrPrintResultCards(',start)
const body=src.slice(start,end)
test('unverified WhatsApp academic marks writer is fully fail closed',()=>{
 assert.ok(start>=0&&end>start)
 assert.ok(body.includes("code: 'SIGNED_MARKS_ACTOR_REQUIRED'"))
 assert.ok(body.includes('success: false'))
 assert.ok(body.includes('processed: 0'))
 assert.ok(!body.includes('queryDb('))
 assert.ok(!body.includes('INSERT INTO'))
 assert.ok(!body.includes('UPDATE exam_results'))
 assert.ok(src.includes('enterExamMarks,'))
})
test('real Grade 9 result write API remains distinct from cognitive tool',()=>{
 const exam=fs.readFileSync(path.join(__dirname,'../routes/examRoutes.js'),'utf8')
 assert.ok(exam.includes('canWriteMarks'))
 assert.ok(exam.includes('examId === 9'))
})
