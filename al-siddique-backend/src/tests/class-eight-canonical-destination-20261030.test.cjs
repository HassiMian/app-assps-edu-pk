'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const sql=fs.readFileSync(path.join(__dirname,'../../../ops/release/class8-promotion/010_canonical_pre_nine_destination.sql'),'utf8')
test('approved destination is canonical SaaS Pre Nine / Blue rather than obsolete Pre-Nine',()=>{
 assert.match(sql,/destination_class='Pre Nine',destination_section='Blue'/)
 assert.match(sql,/CHECK \(source_class='Eight' AND destination_class='Pre Nine'\)/)
 assert.match(sql,/NEW\.class IS DISTINCT FROM policy\.destination_class/)
 assert.ok(sql.indexOf("UPDATE public.school_class_promotion_plans")<sql.indexOf("ADD CONSTRAINT school_class_promotion_plans_check"))
})
test('school roster, subject maxima, marks, and printed evidence remain mandatory',()=>{
 assert.match(sql,/CLASS_EIGHT_PROMOTION_AWAITS_PRINT_APPROVAL/)
 assert.match(sql,/CLASS_EIGHT_PAPER_MAXIMA_NOT_FULLY_APPROVED/)
 assert.match(sql,/CLASS_EIGHT_STUDENT_MARKS_NOT_COMPLETE_OR_DENOMINATOR_MISMATCH/)
 assert.match(sql,/official_offerings<>policy.expected_subject_count/)
 assert.match(sql,/complete_papers<>policy.expected_subject_count/)
 assert.match(sql,/policy\.print_verified_at IS NULL/)
 assert.match(sql,/policy\.academic_approved_at IS NULL/)
 assert.match(sql,/school_id=1 AND class='Eight'/)
 assert.doesNotMatch(sql,/DISABLE TRIGGER/i)
 assert.doesNotMatch(sql,/UPDATE\s+(?:public\.)?(?:exam_results|exam_subjects)\s+SET/i)
})
