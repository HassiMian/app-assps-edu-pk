'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const {cleanNotice,KINDS}=require('../services/documents/schoolDocumentContract')
test('School document taxonomy contains all official categories',()=>{
 assert(KINDS.includes('bell_schedule'))
 assert(KINDS.includes('general_datesheet'))
 assert(KINDS.includes('academic_timetable'))
 assert(KINDS.includes('staff_acknowledgement'))
})
test('Payload requires valid kind, title and plain body',()=>{
 assert(cleanNotice({document_kind:'unknown',title:'a',content:{}}).errors.length>=2)
 assert.deepEqual(cleanNotice({document_kind:'notice',title:'Parents Meeting',content:{message:'PTM scheduled'}}).errors,[])
})
test('Client-supplied identity and unsafe HTML fields are never persisted by document contract',()=>{
 const {value}=cleanNotice({school_id:999,student_id:987,recipient_ids:[2,4],document_kind:'notice',title:'Test Office Notice',content:{message:'<script>alert(1)</script>',student_name:'Private Student',is_published:true}})
 assert(!('school_id' in value))
 assert(!('student_id' in value))
 assert(!('student_name' in value.content))
 assert(!('is_published' in value.content))
 assert.equal(value.content.message,'<script>alert(1)</script>')
})
test('Audiences, source rows and layout are bounded',()=>{
 const {errors,value}=cleanNotice({document_kind:'bell_schedule',title:'Official Bell Schedule',audience_kind:'school',layout_key:'prism',content:{schedule_rows:Array.from({length:250},(_,i)=>({label:'Period '+i,start:'08:00',end:'08:40',student_id:i}))}})
 assert.deepEqual(errors,[])
 assert.equal(value.content.schedule_rows.length,100)
 assert(!('student_id' in value.content.schedule_rows[0]))
})
test('SQL migration is additive with signed-tenant RLS and no record destruction',()=>{
 const source=fs.readFileSync(path.resolve(__dirname,'../../../ops/release/document-studio/001_school_document_drafts.sql'),'utf8')
 assert(source.includes('FORCE ROW LEVEL SECURITY'))
 assert(source.includes('core_security.signed_school_allowed(school_id)'))
 assert(source.includes('REVOKE ALL'))
 assert(!/\b(?:TRUNCATE|DROP TABLE|DELETE FROM|UPDATE\s+(?:students|exam_results|marks|timetable))\b/i.test(source))
 assert.equal((source.match(/^BEGIN;/gm)||[]).length,1)
 assert.equal((source.match(/^COMMIT;/gm)||[]).length,1)
})
test('Studio source routes only enumerate class date-sheet fields, never student names',()=>{
 const source=fs.readFileSync(path.resolve(__dirname,'../routes/schoolDocumentStudioRoutes.js'),'utf8')
 const slice=source.split("router.get('/sources/general-datesheet'")[1].split("router.get('/',")[0]
 assert(slice.includes('school_id=$1'))
 assert(!/SELECT\s+\*/i.test(slice))
 assert(slice.includes('class_level'))
 assert(slice.includes('date_sheet_records'))
 assert(!/\b(?:student_id|student_name|marks_obtained)\b/i.test(slice.split('FROM public.date_sheet_records')[0].split('const result=await query(')[1]))
 assert(source.includes('SELF_APPROVAL_NOT_ALLOWED'))
 assert(source.includes('OFFICIAL_SOURCE_REATTESTATION_REQUIRED'))
})
