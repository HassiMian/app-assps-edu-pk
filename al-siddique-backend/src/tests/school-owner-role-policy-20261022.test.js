'use strict'
const test=require('node:test'),assert=require('node:assert/strict')
const {canUseSchoolRole}=require('../services/schoolOwnerRolePolicy')
test('owner inherits only school admin and principal gates without changing actor identity',()=>{
 assert.equal(canUseSchoolRole('owner',['admin']),true)
 assert.equal(canUseSchoolRole('owner',['principal']),true)
 assert.equal(canUseSchoolRole('owner',['principal','teacher']),true)
 assert.equal(canUseSchoolRole('owner',['teacher']),false)
 assert.equal(canUseSchoolRole('owner',['parent']),false)
 assert.equal(canUseSchoolRole('owner',['super_admin']),false)
 assert.equal(canUseSchoolRole('owner',['platform_owner']),false)
 assert.equal(canUseSchoolRole('owner',[]),false)
})
test('other roles never gain owner capabilities by inheritance',()=>{
 assert.equal(canUseSchoolRole('admin',['principal']),false)
 assert.equal(canUseSchoolRole('admin',['owner']),false)
 assert.equal(canUseSchoolRole('principal',['owner']),false)
 assert.equal(canUseSchoolRole('teacher',['admin']),false)
 assert.equal(canUseSchoolRole('super_admin',['owner']),false)
 assert.equal(canUseSchoolRole('owner',['owner']),true)
 assert.equal(canUseSchoolRole('Principal',['principal']),true)
})
test('role inheritance does not alter signed actor and never becomes platform RLS override',()=>{
 const fs=require('node:fs'),path=require('node:path')
 const mid=fs.readFileSync(path.resolve(__dirname,'../middleware/auth.js'),'utf8')
 const tenant=fs.readFileSync(path.resolve(__dirname,'../middleware/tenant.js'),'utf8')
 assert.ok(mid.includes('canUseSchoolRole(req.user?.role,roles)'))
 assert.ok(mid.includes("const isSuperAdmin = role === 'super_admin' || role === 'platform_owner'"))
 assert.ok(!mid.includes("const isSuperAdmin = role === 'owner'"))
 assert.ok(!tenant.includes("const isPlatform = role === 'owner'"))
})
