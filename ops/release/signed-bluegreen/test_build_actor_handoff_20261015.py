"""Synthetic/negative tests: unsigned review requests cannot be certificates."""
import importlib.util,json,pathlib,unittest
from types import SimpleNamespace
PATH=pathlib.Path(__file__).with_name('build-actor-handoff-20261015.py')
spec=importlib.util.spec_from_file_location('actor_handoff',PATH)
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
def fake(ok=True):
 return SimpleNamespace(CORE_BASE='a'*40,CONNECT_SHA='b'*40,WORKER_SHA='c'*64,
  CONNECT_BUILD='privatebuild',CONNECT_PROXY_SHA='d'*64,BLUE_BUILD='livebuild',
  BLUE_ARCHIVE_SHA='e'*64,DB_DUMP_SHA='f'*64,current_releases=lambda:{'reviewed':ok,'baseline':True})
class ProofIsNotSignature(unittest.TestCase):
 def test_packet_always_hold_even_with_all_green(self):
  p=m.construct(fake());self.assertTrue(p['technical_stage_pass']);self.assertEqual(p['status'],'HOLD')
 def test_no_autogenerated_actor_identity(self):
  p=m.construct(fake());self.assertFalse(p['actor_authenticated']);self.assertFalse(p['independent_human_signed'])
 def test_each_action_unverified(self):
  p=m.construct(fake());self.assertEqual(len(p['tasks']),5);self.assertTrue(all(x['status'] in ('NOT_VERIFIED','HOLD') for x in p['tasks']))
 def test_stage_negative_remains_negative(self):
  p=m.construct(fake(False));self.assertFalse(p['technical_stage_pass']);self.assertEqual(p['status'],'HOLD')
 def test_no_secret_schema_fields(self):
  s=json.dumps(m.construct(fake())).lower()
  for forbidden in ('password_value','access_token','refresh_token','session_cookie','private_key_pem','signature_b64'):
   self.assertNotIn('"'+forbidden+'"',s)
 def test_release_is_never_auto_authorized(self):
  p=m.construct(fake());self.assertIs(p['public_deployed'],False)
if __name__=='__main__':unittest.main(verbosity=2)
