-- Preserve original Class Eight Blue cohort membership BEFORE later Pre-Nine
-- promotion; not a result-card print receipt or approval; NO score data changed.
BEGIN;
SET TRANSACTION ISOLATION LEVEL REPEATABLE READ;
SET LOCAL lock_timeout='2500ms';
SET LOCAL statement_timeout='30000ms';
DO $pre$
BEGIN
 IF current_user<>'postgres'
 OR current_database() NOT IN ('apexos','assps_timetable_9staff_qa_20261014')
 OR (SELECT count(*) FROM public.school_class_promotion_plans
   WHERE school_id=1 AND exam_id=9 AND source_class='Eight'
     AND source_section='Blue' AND destination_class='Pre-Nine'
     AND baseline_student_count=11
     AND status='AWAITING_RESULTS_AND_PRINT'
     AND print_verified_at IS NULL AND executed_at IS NULL)<>1
 OR (SELECT count(*) FROM public.students WHERE school_id=1
     AND class='Eight' AND section='Blue' AND is_active)<>11
 OR (SELECT count(*) FROM public.students WHERE school_id=1
     AND class='Pre-Nine')<>0
 OR (SELECT count(*) FROM information_schema.tables
     WHERE table_schema='public'
       AND table_name='school_class_promotion_source_roster')<>0
 OR (SELECT count(*) FROM pg_trigger WHERE tgname='assps_class8_print_gate_20261014'
     AND NOT tgisinternal)<>1
 THEN RAISE EXCEPTION 'SOURCE_ROSTER_PRECONDITION_OR_TARGET_CHANGED'; END IF;
END $pre$;
CREATE TABLE public.school_class_promotion_source_roster (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 plan_id bigint NOT NULL REFERENCES public.school_class_promotion_plans(id)
   ON DELETE RESTRICT,
 school_id integer NOT NULL REFERENCES public.schools(id) ON DELETE RESTRICT,
 student_id integer NOT NULL REFERENCES public.students(id) ON DELETE RESTRICT,
 historical_exam_id integer NOT NULL REFERENCES public.exams(id) ON DELETE RESTRICT,
 source_class varchar(40) NOT NULL,
 source_section varchar(40) NOT NULL,
 captured_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 policy_source text NOT NULL DEFAULT
  '2026-10-14 protected Eight/Blue roster BEFORE student promotion',
 UNIQUE(plan_id,student_id),
 CHECK (historical_exam_id=9 AND source_class='Eight' AND source_section='Blue')
);
REVOKE ALL ON public.school_class_promotion_source_roster FROM PUBLIC;
ALTER TABLE public.school_class_promotion_source_roster ENABLE ROW LEVEL SECURITY;
-- Nonowner signed Core runtime is subject to RLS. Remain non-FORCE until
-- current deployed restricted core catalog counts are updated beyond 77.
CREATE POLICY source_roster_signed_school_read_20261014
 ON public.school_class_promotion_source_roster FOR SELECT
 TO assps_core_green_runtime
 USING (core_security.signed_school_allowed(school_id));
GRANT SELECT ON public.school_class_promotion_source_roster
 TO assps_core_green_runtime;
CREATE INDEX source_roster_school_student_idx
 ON public.school_class_promotion_source_roster(school_id,student_id);
INSERT INTO public.school_class_promotion_source_roster
(plan_id,school_id,student_id,historical_exam_id,source_class,source_section)
SELECT p.id,p.school_id,s.id,p.exam_id,s.class,s.section
FROM public.school_class_promotion_plans p
JOIN public.students s ON s.school_id=p.school_id
  AND s.class=p.source_class AND s.section=p.source_section AND s.is_active
WHERE p.school_id=1 AND p.exam_id=9
 AND p.source_class='Eight' AND p.source_section='Blue'
 AND p.status='AWAITING_RESULTS_AND_PRINT';
DO $post$
BEGIN
 IF (SELECT count(*) FROM public.school_class_promotion_source_roster)<>11
 OR (SELECT count(DISTINCT student_id) FROM
     public.school_class_promotion_source_roster)<>11
 OR (SELECT count(*) FROM public.school_class_promotion_source_roster r
     JOIN public.students s ON s.id=r.student_id
     WHERE r.school_id<>s.school_id OR s.class<>r.source_class
       OR s.section<>r.source_section)<>0
 OR (SELECT count(*) FROM public.students WHERE school_id=1
     AND class='Eight' AND section='Blue' AND is_active)<>11
 OR (SELECT count(*) FROM public.school_class_promotion_plans WHERE
     school_id=1 AND status='AWAITING_RESULTS_AND_PRINT')<>1
 THEN RAISE EXCEPTION 'SOURCE_ROSTER_SNAPSHOT_INTEGRITY_FAILED'; END IF;
END $post$;
COMMIT;
