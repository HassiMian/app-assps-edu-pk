-- ASSPS promotion policy PLAN ONLY. No students/marks/grade assignments are edited.
-- School1 Class Eight Blue First Term 2026–27 is final assessment FOR PROMOTION.
-- Result cards must be fully printed and verified before any move to Pre-Nine.
BEGIN;
SET LOCAL lock_timeout='2500ms';
SET LOCAL statement_timeout='30000ms';
DO $guard$
BEGIN
 IF current_database() NOT IN ('apexos','assps_timetable_9staff_qa_20261014')
 OR current_user <> 'postgres'
 OR (SELECT count(*) FROM students WHERE school_id=1 AND class='Eight'
      AND section='Blue' AND is_active)=0
 OR (SELECT count(*) FROM exam_subjects WHERE school_id=1 AND exam_id=9
      AND class_name='Eight' AND section='Blue' AND is_active)<>7
 OR (SELECT count(*) FROM exams WHERE school_id=1 AND id=9
      AND name='First Term Exam' AND session='2026-2027')<>1
 OR (SELECT count(*) FROM grade_settings WHERE school_id=1 AND label='F'
      AND min_percentage=0 AND max_percentage=39)<>1
 OR (SELECT count(*) FROM information_schema.tables WHERE table_schema='public'
      AND table_name='school_class_promotion_plans')<>0
 THEN RAISE EXCEPTION 'PROMOTION_POLICY_SOURCE_OR_SCHOOL_CHANGED'; END IF;
END $guard$;
CREATE TABLE public.school_class_promotion_plans (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_id integer NOT NULL REFERENCES public.schools(id),
 exam_id integer NOT NULL REFERENCES public.exams(id),
 academic_session varchar(32) NOT NULL,
 source_class varchar(40) NOT NULL,
 source_section varchar(40) NOT NULL,
 destination_class varchar(40) NOT NULL,
 destination_section varchar(40),
 exam_purpose_for_source_class varchar(80) NOT NULL,
 historical_exam_name varchar(100) NOT NULL,
 passing_percentage integer NOT NULL CHECK (passing_percentage BETWEEN 1 AND 100),
 baseline_student_count integer NOT NULL CHECK (baseline_student_count>0),
 expected_subject_count integer NOT NULL CHECK (expected_subject_count>0),
 status varchar(48) NOT NULL DEFAULT 'AWAITING_RESULTS_AND_PRINT'
 CHECK (status IN ('AWAITING_RESULTS_AND_PRINT','ACADEMIC_REVIEW','READY_FOR_APPROVED_PROMOTION','COMPLETED')),
 print_verified_at timestamptz,
 print_verified_by_user_id integer,
 result_snapshot_sha256 char(64),
 academic_approved_at timestamptz,
 academic_approved_by_user_id integer,
 executed_at timestamptz,
 policy_source text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 CHECK (source_class='Eight' AND destination_class='Pre-Nine'),
 CHECK (exam_purpose_for_source_class='FINAL_TERM_EQUIVALENT_FOR_PROMOTION'),
 CHECK (status='AWAITING_RESULTS_AND_PRINT' OR
        (print_verified_at IS NOT NULL AND print_verified_by_user_id IS NOT NULL
          AND result_snapshot_sha256 IS NOT NULL)),
 CHECK (status NOT IN ('READY_FOR_APPROVED_PROMOTION','COMPLETED') OR
      (academic_approved_at IS NOT NULL AND academic_approved_by_user_id IS NOT NULL
       AND destination_section IS NOT NULL)),
 CHECK (status <> 'COMPLETED' OR executed_at IS NOT NULL),
 UNIQUE (school_id,exam_id,source_class,source_section)
);
ALTER TABLE public.school_class_promotion_plans ENABLE ROW LEVEL SECURITY;
CREATE POLICY school_class_promotion_plan_signed_read
 ON public.school_class_promotion_plans FOR SELECT TO assps_core_green_runtime
 USING (core_security.signed_school_allowed(school_id));
REVOKE ALL ON public.school_class_promotion_plans FROM PUBLIC;
GRANT SELECT ON public.school_class_promotion_plans TO assps_core_green_runtime;
INSERT INTO public.school_class_promotion_plans
(school_id,exam_id,academic_session,source_class,source_section,destination_class,
 exam_purpose_for_source_class,historical_exam_name,passing_percentage,
 baseline_student_count,expected_subject_count,policy_source)
SELECT 1,9,'2026-2027','Eight','Blue','Pre-Nine',
 'FINAL_TERM_EQUIVALENT_FOR_PROMOTION','First Term Exam',40,
 (SELECT count(*) FROM public.students
  WHERE school_id=1 AND class='Eight' AND section='Blue' AND is_active),
 7,'User institutional directive 2026-10-14: Class Eight First Term treated as final promotion assessment; print cards before promotion; Grade IX had no First Term exam.';
DO $post$
BEGIN
 IF (SELECT count(*) FROM public.school_class_promotion_plans)<>1 OR
 (SELECT count(*) FROM public.school_class_promotion_plans WHERE school_id=1
    AND exam_id=9 AND status='AWAITING_RESULTS_AND_PRINT'
    AND print_verified_at IS NULL AND academic_approved_at IS NULL
    AND destination_section IS NULL AND executed_at IS NULL)<>1
 OR (SELECT count(*) FROM public.students WHERE school_id=1
    AND class='Eight' AND section='Blue' AND is_active)=0
 OR (SELECT count(*) FROM public.teacher_class_assignments
    WHERE school_id=1 AND is_active)<>0
 THEN RAISE EXCEPTION 'PROMOTION_PLAN_MUST_NOT_MOVE_OR_GRANT'; END IF;
END $post$;
COMMIT;
