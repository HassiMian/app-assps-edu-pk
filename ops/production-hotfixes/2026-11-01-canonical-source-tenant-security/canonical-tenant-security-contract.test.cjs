'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path')
const root=path.join(__dirname,'../../../al-siddique-backend/src')
const ops=fs.readFileSync(path.join(root,'routes/opsRoutes.js'),'utf8')
const paper=fs.readFileSync(path.join(root,'routes/paperRoute.js'),'utf8')
const staff=fs.readFileSync(path.join(root,'routes/employeeRoutes.js'),'utf8')
const {canManageGlobalAiQueue}=require(path.join(root,'services/ai/globalAiQueueAuthority.js'))
const {employeePublicRecord}=require(path.join(root,'services/staffSecurityProjection.js'))
test('global telemetry withheld from school-level Principal and Admin',()=>{
 assert.match(ops,/isSuperAdmin \? getQueueStats\(\) : null/)
 assert.match(ops,/isSuperAdmin \? await listQueueEvents\(1\) : \[\]/)
 assert.match(ops,/isSuperAdmin \? query\(/)
 assert.match(ops,/withheld_global_queue_not_school_scoped/)
 assert.match(ops,/recentOutcomes24h: outcomes/)
 assert.match(ops,/failureRate24h: queueOutcomeR \? health\.failureRate24h : null/)
})
test('school-wide queue pause/resume requires platform superadmin',()=>{
 assert.equal(canManageGlobalAiQueue({role:'principal'}),false)
 assert.equal(canManageGlobalAiQueue({role:'admin'}),false)
 assert.equal(canManageGlobalAiQueue({role:'super_admin'}),true)
 assert.match(paper,/if \(canManageGlobalAiQueue\(req\.user\)\) return true/)
 assert.match(paper,/GLOBAL_QUEUE_SUPER_ADMIN_ONLY/)
 assert.equal((paper.match(/if \(!requireQueueAdmin\(req, res\)\) return/g)||[]).length,2)
})
test('staff credential not serialized by standard employee API',()=>{
 const safe=employeePublicRecord({id:3,name:'Synthetic',portal_password:'SYNTHETIC_VALUE'})
 assert.equal(safe.portal_password,undefined)
 assert.equal(safe.name,'Synthetic')
 assert.match(staff,/result\.rows\.map\(employeePublicRecord\)/)
 assert.match(staff,/employeePublicRecord\(updated\)/)
})
test('raw credential requests rejected from staff create and update',()=>{
 assert.match(staff,/LEGACY_PORTAL_PASSWORD_FIELD_FORBIDDEN/)
 assert.equal((staff.match(/if \(rejectLegacyPortalPasswordWrite\(req,res\)\) return/g)||[]).length,2)
 const fields=staff.slice(staff.indexOf('const EMPLOYEE_WRITE_FIELDS'),staff.indexOf('async function existingEmployeeWriteFields'))
 assert.doesNotMatch(fields,/portal_password/)
})
