'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path')
const m=require('../qbank/verify-grade910-private-all2581-delivery-20261015.cjs')
const base='/root/secure-archive/assps-grade910-review-delivery-20261015'
const runId='grade910-20261015-full'
test('private school handoff attests 2580 source-sealed faculty packets and 56 unsigned adopted-book forms',()=>{
 const a=m.inspect({base,runId})
 assert.equal(a.originalResearchQuestionCount,2581)
 assert.equal(a.privateBlindAndAnswerReferenceQuestions,2580)
 assert.equal(a.unsignedQualifiedTeacherForms,2580)
 assert.equal(a.unsignedTextbookAdoptionForms,56)
 assert.equal(a.questionReviewBatchCount,120)
 assert.equal(a.sourceReviewGroups,56)
 assert.equal(a.facultyHeldOriginalId,'X-CHEM-C23-L01')
 assert.equal(a.groups.reduce((v,g)=>v+g.originalResearchItems,0),2581)
 assert.equal(a.groups.reduce((v,g)=>v+g.readyForIndependentReview,0),2580)
 assert.equal(a.groups.reduce((v,g)=>v+g.excludedHeld,0),1)
 assert.equal(a.teacherReviewsAuthenticated,0)
 assert.equal(a.principalAcademicApprovals,0)
 assert.equal(a.academicallyApproved,0)
 assert.equal(a.published,0)
})
test('private delivery source and on-disk byte manifest remain immutable at locked 0600 permissions',()=>{
 const v=m.verifyFrozen({base,runId})
 assert.equal(v.groups,56)
 assert.equal(v.unsignedFaculty,2580)
 assert.equal(v.adoptionForms,56)
 assert.equal(v.published,false)
 const file=path.join(base,'PRIVATE_HANDOFF_GROUP_CROSSWALK.json')
 assert.equal(fs.statSync(file).mode&0o777,0o600)
 assert.equal(fs.statSync(base).mode&0o777,0o700)
 assert.ok(!JSON.stringify(JSON.parse(fs.readFileSync(m.SUMMARY))).includes('answerTextOriginalCandidateOnly'))
})
test('private delivery never writes inside source repo or follows caller-provided unsafe folders',()=>{
 const inside=path.resolve(__dirname,'../..')
 assert.throws(()=>m.safeDir(inside),/(PRIVATE_DELIVERY_INSIDE_PUBLIC_REPOSITORY|PRIVATE_DIRECTORY_UNTRUSTED)/)
 assert.throws(()=>m.inspect({base:inside,runId}),/(PRIVATE_DELIVERY_INSIDE_PUBLIC_REPOSITORY|PRIVATE_DIRECTORY_UNTRUSTED)/)
 assert.throws(()=>m.inspect({base,runId:'../../unsafe'}),/INVALID_DELIVERY_RUN_ID/)
})
test('public metadata summary contains only aggregate hashes, not option/answer or teacher signature fields',()=>{
 const record=JSON.parse(fs.readFileSync(m.SUMMARY))
 assert.equal(record.originalResearchQuestionCount,2581)
 assert.equal(record.questionReviewBatchCount,120)
 assert.equal(record.teacherReviewsAuthenticated,0)
 assert.equal(record.academicallyApproved,0)
 assert.equal(record.published,0)
 assert.equal(record.productionWritePermitted,false)
 assert.equal(Object.hasOwn(record,'groups'),false)
 for(const key of ['questionText','answers','answerKey','signature','studentName','reviewerName'])
  assert.equal(Object.hasOwn(record,key),false)
})
test('immutable complete private handoff refuses overwrite or regeneration of existing review evidence',()=>{
 assert.throws(()=>m.write({base,runId}),/NONDESTRUCTIVE_PRIVATE_ATTESTATION_ALREADY_EXISTS/)
 assert.equal(m.verifyFrozen({base,runId}).published,false)
})
test('offline faculty HTML remains source-index batch count matched, unsigned, script-free and private',()=>{
 const render=require('../qbank/render-grade910-private-faculty-review.cjs')
 const b=path.join(base,'packets'),renderId='offline-readable-20261015'
 const result=render.verifyRendered({base:b,runId,renderId})
 assert.equal(result.verifiedHtmlFiles,360)
 assert.equal(result.privateCandidates,2580)
 assert.equal(result.heldOutside,1)
 assert.equal(result.academicApproved,0)
 assert.equal(result.studentPublication,false)
 const root=path.join(b,runId,renderId)
 assert.equal(fs.statSync(root).mode&0o777,0o700)
 const index=JSON.parse(fs.readFileSync(path.join(root,'RENDERED_INDEX.json')))
 assert.equal(index.originalBatches,120)
 assert.equal(index.files.length,360)
 assert.equal(index.reviewerSignaturesAuthenticated,0)
})
