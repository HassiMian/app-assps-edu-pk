'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path')
const m=require('../qbank/prepare-grade910-private-faculty-quality-overlay-20261015.cjs')
const base='/root/secure-archive/assps-grade910-review-delivery-20261015',runId='grade910-20261015-full'
let data
const get=()=>data||(data=m.assemble({base,runId}))
test('source-locked private reviewer roster covers every eligible original and all 56 groups',()=>{
 const d=get(),ids=d.groups.flatMap(g=>g.items.map(i=>i.originalId))
 assert.equal(d.candidateOriginals,2581)
 assert.equal(d.privateReviewReady,2580)
 assert.equal(d.schoolReviewGroups,56)
 assert.equal(ids.length,2580)
 assert.equal(new Set(ids).size,2580)
 assert.equal(d.unresolvedChemistrySourceId,'X-CHEM-C23-L01')
 assert.ok(!ids.includes(d.unresolvedChemistrySourceId))
})
test('all existing specific risks route with 166 rubric cases minus the held one',()=>{
 const x=get().signals
 assert.equal(x.ORIGINAL_KEY_A_OVERCONCENTRATION_EDIT_REVIEW_NOT_CORRECTNESS,785)
 assert.equal(x.SOURCE_CONSECUTIVE_MCQ_KEY_REPEAT_IN_FILE,724)
 assert.equal(x.RUBRIC_LIKE_LONG_ANSWER_NOT_COMPLETE_MODEL_ANSWER,165)
 assert.equal(x.MCQ_SOURCE_ANSWER_TEXT_KEY_POSITION_ONLY_INFERRED,24)
 assert.equal(x.POTENTIAL_NEAR_STEM_REUSE_INDEPENDENT_DUPLICATE_REVIEW,15)
 assert.equal(x.REVISED_MCQ_AI_DISTRACTORS_AWAIT_FACTUAL_REVIEW,66)
 assert.equal(x.MCQ_NEW_DISTRACTOR_ABSOLUTE_WORD_CUE,54)
})
test('blank faculty decisions never become published choices because of the quality ranking',()=>{
 const d=get()
 assert.equal(d.genuineTeacherReviews,0)
 assert.equal(d.genuineBookAdoptions,0)
 assert.equal(d.academicallyApproved,0)
 assert.equal(d.published,0)
 assert.equal(d.productionWrites,0)
 for(const g of d.groups)for(const row of g.items){
  assert.equal(row.qualifiedReviewerValidated,false)
  assert.equal(row.referenceAnswerIndependentVerification,false)
  assert.equal(row.paperStudioSelectable,false)
  assert.match(row.sourceQuestionRevisionSha256,/^[0-9a-f]{64}$/)
 }
})
test('rendered private metadata is owner-only and exactly stable across independent verification',()=>{
 const r=m.verify({base,runId})
 assert.equal(r.privateQuestions,2580)
 assert.equal(r.authenticatedSchoolReviews,0)
 assert.equal(r.published,0)
 assert.equal(fs.statSync(path.join(base,m.NAME)).mode&0o777,0o600)
 assert.equal(fs.statSync(base).mode&0o777,0o700)
})
test('re-running the authoring builder cannot silently overwrite the private reviewer assignment',()=>{
 assert.throws(()=>m.guardedWrite({base,runId}),/IMMUTABLE_PRIORITY_FILE_ALREADY_EXISTS/)
})
test('public record exposes metadata checksum, not confidential packet text or signatures',()=>{
 const d=JSON.parse(fs.readFileSync(m.PUBLIC,'utf8'))
 assert.equal(d.sourceOriginals,2581)
 assert.equal(d.privateFacultyQuestions,2580)
 assert.equal(d.reviewGroups,56)
 assert.equal(d.schoolBooksAdoptedAuthenticated,0)
 assert.equal(d.academicallyApproved,0)
 assert.equal(d.published,0)
 assert.equal(Object.hasOwn(d,'groups'),false)
 for(const name of ['stem','answer','answerKey','reviewerName','staffSignature','studentName'])
  assert.equal(Object.hasOwn(d,name),false)
})
test('offline teacher dashboard links to verified blind packets only, never reference answers',()=>{
 const v=require('../qbank/render-grade910-private-quality-index-20261015.cjs')
 const result=v.verify({base,runId})
 assert.equal(result.privateGroups,56)
 assert.equal(result.sourceQuestions,2580)
 assert.equal(result.approved,0)
 const html=fs.readFileSync(path.join(base,v.NAME),'utf8')
 assert.ok(html.includes('Content-Security-Policy'))
 assert.ok(html.includes('default-src &#39;none&#39;'))
 assert.ok(html.includes('.blind.html'))
 assert.ok(!html.includes('.reference.html'))
 assert.ok(!html.includes('.answer-review.json'))
 assert.ok(!html.includes('<script'))
 assert.equal(fs.statSync(path.join(base,v.NAME)).mode&0o777,0o600)
 assert.throws(()=>v.create({base,runId}),/CANNOT_REWRITE_FROZEN_PRIVATE_INDEX/)
})
