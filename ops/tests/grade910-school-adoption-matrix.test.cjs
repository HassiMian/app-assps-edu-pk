'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs')
const m=require('../qbank/build-grade910-school-adoption-verification-matrix.cjs')
let cache
const current=()=>cache??(cache=m.build())
test('full PECTAA source catalog mapped to complete 2581 frozen research candidate claims',()=>{
 const x=current()
 assert.equal(x.originalCandidates,2581)
 assert.equal(x.catalogEntries,111)
 assert.equal(x.catalogReferencedByOriginals,56)
 assert.equal(x.catalogUnreferencedByOriginals,55)
 assert.equal(x.rows.length,111)
 assert.equal(new Set(x.rows.map(r=>r.catalogId)).size,111)
 assert.equal(x.rows.reduce((a,r)=>a+r.originalResearchCandidateCount,0),2581)
})
test('cross-grade Urdu writing source has 70 original claims requiring human class applicability',()=>{
 const x=current(),r=x.rows.find(q=>q.catalogId==='pectaa-catalog-107')
 assert.equal(r.gradeCatalogClaim,0)
 assert.equal(r.originalResearchCandidateCount,70)
 assert.equal(x.sharedGradeUnassignedCatalogOriginals,70)
 assert.ok(r.warnings.includes('NON_GRADE_SPECIFIC_CATALOG_ENTRY'))
})
test('no catalog PDF SHA or publication can impersonate ASSPS textbook adoption or qualified review',()=>{
 const x=current()
 assert.equal(x.schoolAdoptionCertificatesAuthenticated,0)
 assert.equal(x.gradeAndSubjectBookEditionSchoolVerified,0)
 assert.equal(x.reviewedSchoolApplicableExamYear,null)
 assert.equal(x.originalsWithMissingOwnPdfSha256,44)
 assert.equal(x.approvedQuestions,0)
 assert.equal(x.publishedQuestions,0)
 assert.equal(x.publisherSelectable,0)
 assert.ok(x.rows.every(q=>q.actualSchoolAdoptedBookVerified===false))
 assert.ok(x.rows.every(q=>q.schoolAdoptionEvidenceSha256===null))
 assert.ok(x.rows.every(q=>q.verifiedPaperStudioSelectable===false))
})
test('reproducible source-only catalog matrix is complete and contains no original question texts',()=>{
 const disk=JSON.parse(fs.readFileSync(m.OUT,'utf8'))
 assert.deepEqual(disk,current())
 assert.equal(fs.readFileSync(m.NOTE,'utf8'),m.markdown(current()))
 assert.ok(disk.rows.every(x=>!Object.hasOwn(x,'questionText')&&!Object.hasOwn(x,'answer')))
})
