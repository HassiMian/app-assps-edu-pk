"""Actual original frozen Grade X Urdu Biology 10-question research answer QA."""
import copy,importlib.util,json
from pathlib import Path
import unittest
ROOT=Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location('bio10_urdu_author',ROOT/'ops/qbank/author-grade10-urdu-biology-ten-research-answers-20261016.py')
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
class Biology10UrduOriginalResearchTests(unittest.TestCase):
 @classmethod
 def setUpClass(cls):
  cls.packet=json.loads(m.OUT.read_text(encoding='utf8'))
 def test_exactly_ten_distinct_current_revision_bound_answers(self):
  rows=self.packet['newAnswers']
  self.assertEqual(len(rows),10)
  self.assertEqual({r['questionId'] for r in rows},set(m.PROPOSALS))
  self.assertTrue(all(len(r['currentLiveRevisionSha256'])==64 for r in rows))
 def test_all_ten_independent_explanations_are_longer_than_rubrics(self):
  rows=self.packet['newAnswers']
  self.assertTrue(all(len(r['newIndependentResearchAnswerUrdu'].split())>=65 for r in rows))
  self.assertTrue(all(len(r['newIndependentResearchAnswerUrdu'])>360 for r in rows))
 def test_urdu_arabic_script_and_no_latin_only_draft(self):
  for r in self.packet['newAnswers']:
   with self.subTest(id=r['questionId']):
    a=r['newIndependentResearchAnswerUrdu']
    self.assertGreater(sum(0x600<=ord(c)<=0x6ff for c in a),150)
 def test_five_distinct_urdu_criteria_for_five_marks(self):
  for r in self.packet['newAnswers']:
   self.assertEqual(len(set(r['proposedFiveSeparateMarkingCriteriaUrdu'])),5)
   self.assertEqual(r['marks'],5)
 def test_no_fake_teacher_revision_or_institutional_edition_approval(self):
  assert all(r['independentSubjectTeacherReviewed'] is False for r in self.packet['newAnswers'])
  assert all(r['independentUrduLanguageReviewed'] is False for r in self.packet['newAnswers'])
  assert all(r['school2026To2027EditionAdoptionAuthenticated'] is False for r in self.packet['newAnswers'])
  self.assertFalse(self.packet['academicallyApproved'])
  self.assertFalse(self.packet['publishedVerified'])
  self.assertEqual(self.packet['productionDatabaseWrites'],0)
  self.assertTrue(all(not r['paperStudioVerifiedSelectable'] for r in self.packet['newAnswers']))
 def test_factual_background_links_are_explicit_not_invented_textbook_pages(self):
  for r in self.packet['newAnswers']:
   self.assertTrue(r['backgroundFactualReferenceUrl'].startswith('https://'))
   self.assertFalse(r['sourcePageOrExerciseIndependentlyVerified'])
   self.assertIn('originalSourceFileSha256',r)
   self.assertIn('storedResearchChapterNumberUnverified',r)
 def test_packet_exact_content_matches_authored_generator(self):
  frozen={x['id']:x for x in json.loads(m.SOURCE.read_text())['drafts']}
  live={r['questionId']:{'chapter':r['storedResearchChapterNumberUnverified']} for r in self.packet['newAnswers']}
  hashes={r['questionId']:r['currentLiveRevisionSha256'] for r in self.packet['newAnswers']}
  self.assertEqual(self.packet,m.build(live,hashes))
 def test_freeze_original_school_source_file_bytes(self):
  self.assertEqual(m.sha(m.SOURCE.read_bytes()),m.EXPECTED_SOURCE_SHA)
 def test_original_rubric_not_misrepresented_as_new_explanation(self):
  src=json.loads(m.SOURCE.read_text())
  q={d['id']:d['content']['ur'] for d in src['drafts']}
  for row in self.packet['newAnswers']:
   self.assertNotEqual(row['newIndependentResearchAnswerUrdu'],q[row['questionId']]['answer'])
 def test_proposal_tampering_detected_against_generator(self):
  clone=copy.deepcopy(self.packet)
  clone['newAnswers'][0]['academicApproved']=True
  frozen={x['id']:x for x in json.loads(m.SOURCE.read_text())['drafts']}
  live={r['questionId']:{'chapter':r['storedResearchChapterNumberUnverified']} for r in self.packet['newAnswers']}
  hashes={r['questionId']:r['currentLiveRevisionSha256'] for r in self.packet['newAnswers']}
  self.assertNotEqual(clone,m.build(live,hashes))
 def test_source_original_and_current_stem_unchanged(self):
  source={d['id']:d for d in json.loads(m.SOURCE.read_text())['drafts']}
  ids={r['questionId'] for r in self.packet['newAnswers']}
  self.assertEqual(ids,set(m.PROPOSALS))
  for id in ids:
   self.assertTrue(source[id]['content']['ur']['stem'])
   self.assertTrue(source[id]['content']['ur']['answer'])
   self.assertEqual(source[id]['type'],'long')
   self.assertEqual(source[id]['marks'],5)
 def test_source_adopted_and_human_reviewer_not_autogenerated(self):
  self.assertFalse(self.packet['actualSchoolTextbookAdoptionVerified'])
  self.assertFalse(self.packet['exactOriginalExercisePageVerified'])
  self.assertFalse(self.packet['independentQualifiedSubjectReviewed'])
  self.assertFalse(self.packet['independentUrduReviewed'])
if __name__=='__main__':unittest.main()
