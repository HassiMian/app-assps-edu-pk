'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),crypto=require('node:crypto')
const b=require('../qbank/build-grade910-584-evidence-bundle-20261015.cjs')
const SHA=x=>crypto.createHash('sha256').update(x).digest('hex')
test('every flagged research candidate has exactly one source-revision-bound evidence lane',()=>{
 const x=b.assemble()
 assert.equal(x.rows.length,584)
 assert.equal(new Set(x.rows.map(y=>y.originalId)).size,584)
 assert.deepEqual(x.stageCounts,{numerical:61,english:24,longP1:34,mcq:68,longP2:389,essay:8})
 assert.deepEqual(x.priorityCounts,{P1:119,P2:465})
 assert.equal(x.originalResearchCandidatesPreserved,2581)
 assert.deepEqual(JSON.parse(fs.readFileSync(b.out)),x)
})
test('curated 66 proposals are exactly revision-bound subset of 68 source MCQ analyses',()=>{
 const x=b.assemble(),m=x.rows.filter(y=>y.evidenceStage==='mcq')
 assert.equal(m.length,68)
 assert.equal(m.filter(y=>y.individuallyCuratedDistractors).length,66)
 assert.ok(m.filter(y=>y.individuallyCuratedDistractors).every(y=>/^[a-f0-9]{64}$/.test(y.newDistractorProposalHash)))
 assert.equal(m.filter(y=>!y.individuallyCuratedDistractors).length,2)
})
test('typed evidence cannot be confused with textbook source or authentic school signoff',()=>{
 const x=b.assemble()
 for(const q of x.rows){
  assert.equal(q.academicallyApproved,false)
  assert.equal(q.paperStudioSelectable,false)
  assert.equal(q.published,false)
  assert.equal(q.principalAuthenticatedSignedApproval,false)
  assert.equal(q.languageAndSubjectQualifiedReview,false)
  assert.equal(q.adoptedPhysicalTextbookProvenanceVerified,false)
  assert.equal(q.printedExerciseAndPageVerified,false)
  assert.match(q.originalRevisionSha256,/^[a-f0-9]{64}$/)
  assert.equal(x.evidenceFiles[q.evidenceFile],q.evidenceFileSha256)
 }
 assert.equal(x.academicallyApproved,0)
 assert.equal(x.published,0)
})
test('source review queue and exact linked evidence digests are reproducible',()=>{
 const x=b.assemble()
 assert.equal(b.write().digest,SHA(fs.readFileSync(b.out)))
 assert.ok(x.rows.every(y=>y.evidenceFileSha256.length===64))
 const summary=fs.readFileSync(b.md,'utf8')
 assert.match(summary,/584/)
 assert.match(summary,/2,581/)
 assert.match(summary,/Do not directly seed/)
})
test('28 original English 9 authoring items have explicit provisional review routing without invented original identity',()=>{
 const x=b.assemble()
 assert.equal(x.originalMetadataComplete,556)
 assert.equal(x.provisionalGrade9EnglishAuthoringRoute,28)
 assert.equal(x.reviewGrade9,390)
 assert.equal(x.reviewGrade10,194)
 assert.equal(x.reviewEnglish,334)
 assert.equal(x.reviewUrdu,250)
 const inferred=x.rows.filter(r=>!r.originalIdentityFieldsComplete)
 assert.equal(inferred.length,28)
 for(const row of inferred){
  assert.match(row.originalId,/^IX-ENG-ORIG-20261008-/)
  assert.equal(row.grade,null)
  assert.equal(row.subject,null)
  assert.equal(row.medium,null)
  assert.equal(row.reviewRoutingIdentity.grade,9)
  assert.equal(row.reviewRoutingIdentity.subject,'english')
  assert.equal(row.reviewRoutingIdentity.medium,'english')
  assert.equal(row.reviewRoutingIdentity.evidence,'ENGLISH9_AUTHORING_SOURCE_MAP_INFERENCE_ONLY')
  assert.match(row.reviewRoutingIdentity.sourceMapSha256,/^[a-f0-9]{64}$/)
  assert.equal(row.reviewRoutingIdentity.schoolAdoptionCertified,false)
  assert.equal(row.paperStudioSelectable,false)
 }
})
