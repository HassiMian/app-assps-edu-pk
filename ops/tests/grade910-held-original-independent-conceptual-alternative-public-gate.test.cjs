'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),crypto=require('node:crypto'),path=require('node:path')
const root=path.resolve(__dirname,'../..')
const gate=require('../qbank/verify-grade910-held-conceptual-alternative-20261015.cjs')
const data=JSON.parse(fs.readFileSync(gate.PUBLIC,'utf8'))
const sha=x=>crypto.createHash('sha256').update(x).digest('hex')
test('original Grade X Chemistry source question is still SHA-frozen and explicitly held',()=>{
 const pathOriginal=path.join(root,'al-siddique-frontend/src/Modules/Paper-Generator/seed-data/grade9-10-staging/chemistry10Starter2026.json')
 const raw=fs.readFileSync(pathOriginal),original=(JSON.parse(raw).items||JSON.parse(raw).drafts).find(x=>x.id==='X-CHEM-C23-L01')
 assert.equal(sha(raw),data.originalSourceFileSha256)
 assert.equal(sha(JSON.stringify(original)),data.originalQuestionRevisionSha256)
 assert.equal(data.originalRecordFacultyHeld,true)
 assert.equal(data.changeAppliedToOriginal,false)
 assert.equal(data.proposedSeparateDraftId!=='X-CHEM-C23-L01',true)
})
test('five-mark new conceptual draft metadata carries only immutable SHA not private question or answer texts',()=>{
 assert.equal(data.validFiveMarkConceptualDraftPrepared,true)
 assert.match(data.proposedQuestionRevisionSha256,/^[a-f0-9]{64}$/)
 assert.match(data.proposedAnswerRevisionSha256,/^[a-f0-9]{64}$/)
 assert.equal(Object.keys(data.privateRecordHashSummaries).length,3)
 assert.equal(Object.keys(data.privateReviewArtifactsSha256).length,3)
 for(const field of ['question','answer','referenceAnswer','markScheme','blindHtml','teacherName','signature','privateDirectory'])
  assert.equal(Object.hasOwn(data,field),false)
})
test('alternately authored source research may not claim real school authority or enter verified question picker',()=>{
 assert.equal(data.schoolExerciseMatchVerified,false)
 assert.equal(data.needsSchoolAdoptedEditionConfirmation,true)
 assert.equal(data.requiresQualifiedIndependentReview,true)
 assert.equal(data.paperStudioSelectable,false)
 assert.equal(data.approved,0)
 assert.equal(data.published,0)
 assert.match(data.stage,/HOLD/)
})
