'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs')
const m=require('../qbank/verify-grade910-private-all2581-delivery-20261015.cjs')
const a=JSON.parse(fs.readFileSync(m.SUMMARY,'utf8'))
test('public-safe attestation is a SHA-bound, zero-approval accounting of the full private school review handoff',()=>{
 assert.equal(a.originalResearchQuestionCount,2581)
 assert.equal(a.privateBlindAndAnswerReferenceQuestions,2580)
 assert.equal(a.unsignedQualifiedTeacherForms,2580)
 assert.equal(a.unsignedTextbookAdoptionForms,56)
 assert.equal(a.questionReviewBatchCount,120)
 assert.equal(a.sourceReviewGroups,56)
 assert.equal(a.teacherReviewsAuthenticated,0)
 assert.equal(a.academicallyApproved,0)
 assert.equal(a.published,0)
 assert.equal(a.productionWritePermitted,false)
 assert.match(a.privateGroupHandoffSha256,/^[a-f0-9]{64}$/)
 assert.match(a.candidateReviewCrosswalkSha256,/^[a-f0-9]{64}$/)
})
test('published-source proof never exports rendered answer-bearing faculty sheets or personal identifiers',()=>{
 const raw=fs.readFileSync(m.SUMMARY,'utf8')
 for(const field of ['answerTextOriginalCandidateOnly','originalReferenceAnswerText','signatureImage','studentName','reviewerEmail','rootPrivatePath'])
  assert.ok(!raw.includes(field))
 assert.equal(Object.hasOwn(a,'groups'),false)
})
test('special source item with inadequate substantive reference stays held rather than counted as approved',()=>{
 assert.equal(a.facultyHeldOriginalId,'X-CHEM-C23-L01')
 assert.equal(a.originalResearchQuestionCount-a.privateBlindAndAnswerReferenceQuestions,1)
 assert.match(a.status,/PUBLICATION_HOLD/)
})
