'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const base=path.resolve(__dirname,'../../al-siddique-frontend/src/Modules/Paper-Generator')
const src=fs.readFileSync(path.join(base,'Grade910HumanSignoff.jsx'),'utf8')
test('PDF/PNG/JPG binary evidence may not be fabricated by typing a digest',async()=>{
 const {detectSchoolEvidenceMime:detect}=await import(path.join(base,'grade910EvidenceByteProof.mjs'))
 assert.equal(detect(new Uint8Array([37,80,68,70,45,49,46,55])),'application/pdf')
 assert.equal(detect(new Uint8Array([137,80,78,71,13,10,26,10,8])),'image/png')
 assert.equal(detect(new Uint8Array([255,216,255,224])),'image/jpeg')
 assert.equal(detect(new Uint8Array([80,68,70,45,49,46,55])),null)
 assert.equal(detect(new Uint8Array([77,90,0,1,2,3])),null)
 assert.equal(detect(new Uint8Array([])),null)
})
test('signoff uses only computed file-byte digest, verifies magic and resets stale evidence',()=>{
 assert.match(src,/const provenMime=detectSchoolEvidenceMime\(new Uint8Array\(bytes\)\)/)
 assert.match(src,/const hashed=await digest\(bytes\)/)
 assert.match(src,/readOnly value=\{evidenceHash\}/)
 assert.doesNotMatch(src,/setEvidenceHash\)/)
 assert.match(src,/clearEvidence\(\)\s*const selectedAt=evidenceSelectionVersion\.current/)
 assert.match(src,/if\(selectedAt!==evidenceSelectionVersion\.current\)return/)
 assert.match(src,/clearEvidence\(\);setCatalogId/)
 assert.match(src,/clearEvidence\(\);setAction/)
 assert.match(src,/original supporting file/)
 assert.match(src,/Retry original evidence upload/)
 assert.match(src,/application\/octet-stream/)
 assert.match(src,/supportingEvidenceSha256:evidenceHash\|\|null/)
 assert.match(src,/academicallyApproved:false,paperStudioSelectable:false,published:false/)
})
