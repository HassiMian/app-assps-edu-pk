'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const lesson=read('al-siddique-frontend/src/Modules/Paper-Generator/LessonPlanningWorkspace.jsx')
const diary=read('al-siddique-frontend/src/Modules/Paper-Generator/DailyDiaryWorkspace.jsx')
test('Lesson Planning defaults to the identical Daily Diary editor/print renderer',()=>{
 assert.match(lesson,/import DailyDiaryWorkspace from '\.\/DailyDiaryWorkspace'/)
 assert.match(lesson,/useState\('diary-format'\)/)
 assert.match(lesson,/<DailyDiaryWorkspace initialMode="lesson"\/>/)
 assert.match(diary,/mode === 'lesson' \? 'LESSON PLAN' : 'DAILY DIARY'/)
 assert.match(diary,/data-a4-page/)
 assert.match(diary,/StudentCard/)
 assert.match(diary,/subjectFontSize/)
 assert.match(diary,/globalSubjectFontSize/)
})
test('Old weekly/term, advanced editor, and school-server save paths remain intact',()=>{
 assert.match(lesson,/planningView==='weekly'\?<WeeklyNotebookStudio\/>/)
 assert.match(lesson,/Advanced Lesson Editor/)
 assert.match(diary,/createLessonPlan/)
 assert.match(diary,/updateLessonPlan/)
 assert.match(diary,/activeSavedDiaryId/)
 assert.match(diary,/data-diary-mode="diary"/)
 assert.match(diary,/initialMode !== 'lesson'/)
 assert.match(diary,/mode === 'diary' && <button/)
})
test('Notices create a separate school-scoped source system, never replacing historic notices',()=>{
 const server=read('al-siddique-backend/src/server.js')
 assert.match(server,/mount\('\/notices',\s*'\.\/routes\/noticesRoutes'\)/)
 assert.match(server,/mount\('\/school-documents',\s*'\.\/routes\/schoolDocumentStudioRoutes'\)/)
 const routes=read('al-siddique-backend/src/routes/schoolDocumentStudioRoutes.js')
 assert.match(routes,/SELF_APPROVAL_NOT_ALLOWED/)
 assert.match(routes,/OFFICIAL_SOURCE_REATTESTATION_REQUIRED/)
 assert.match(routes,/applyTenantContext\(client\)/)
 assert.doesNotMatch(routes,/SELECT\s+\*\s+FROM public\.date_sheet_records/i)
})
