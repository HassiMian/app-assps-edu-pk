'use strict'
const test=require('node:test'),assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto')
const check=require('../qbank/verify-grade910-processed-correction-integrity-20261014.cjs')
const rooted=path.resolve(__dirname,'../..')
const SHA=x=>crypto.createHash('sha256').update(x).digest('hex')
test('all 584 items match original raw file SHA and immutable question JSON SHA',()=>{
 const rows=check.assess()
 assert.equal(rows.originalsBoundToExactSourceBytesAndRevisionHash,584)
 assert.equal(rows.reviewDocketItems,584)
 assert.deepEqual(rows.priority,{P1:119,P2:465})
 assert.equal(rows.approved,0)
 assert.equal(rows.published,0)
 assert.equal(rows.qualifiedHumanReviewed,0)
 assert.equal(rows.numericalCalculationsIndependentlyRecomputed,0)
})
test('no unverifiable correctness signoff or calculated numerical steps claimed',()=>{
 const rows=check.assess()
 assert.ok(rows.rows.every(x=>x.answerCorrectnessVerified===false&&x.semanticFactCheckPerformed===false))
 assert.ok(rows.rows.every(x=>x.academicallyApproved===false&&x.published===false&&x.paperStudioSelectable===false))
 const math=rows.rows.filter(x=>x.signals.includes('NUMERICAL_WORKING_REVIEW'))
 assert.equal(math.length,61)
 assert.ok(math.every(x=>x.numericalRecalculationPerformed===false&&x.formattingProposal===null))
 assert.ok(math.every(x=>x.verificationQueue==='INDEPENDENT_FORMULA_ARITHMETIC_UNITS_RECALCULATION_REQUIRED'))
 assert.ok(!JSON.stringify(rows).includes('recomputedPassed'))
 assert.ok(!JSON.stringify(rows).includes('Independently recomputed numerical formula'))
})
test('24 MCQ formatting-only proposals cannot invent correct answers or use A fallback',()=>{
 const rows=check.assess()
 assert.equal(rows.mechanicallyProposedMcqOptionLabels,24)
 const mcqs=rows.rows.filter(x=>x.signals.includes('MCQ_KEY_ID_NOT_EXPLICIT'))
 assert.equal(mcqs.length,24)
 assert.ok(mcqs.every(x=>x.formattingProposal?.sourceAnswerNotFactChecked===true))
 assert.ok(mcqs.every(x=>x.formattingProposal?.substantiveAnswerKeyVerified===false))
 assert.deepEqual(mcqs.reduce((t,x)=>(t[x.formattingProposal.referenceAnswerOptionId]++,t),{A:0,B:0,C:0,D:0}),{A:0,B:17,C:7,D:0})
 const broken=check.referenceOnlyMcq({options:['foo','bar','baz','qux'],answer:'missing'})
 assert.equal(broken.status,'UNRESOLVED_REFERENCE_ANSWER_MAPPING')
 assert.equal(broken.formatOnlyDraft,null)
})
test('mutation of any official original file hash or exact question revision is rejected',()=>{
 const original=fs.readFileSync(check.IN),legacy=fs.readFileSync(path.join(rooted,'docs/question-bank/ASSPS_GRADE910_PROCESSED_ACADEMIC_CORRECTIONS_20261014.json'))
 const docket=JSON.parse(original)
 docket.rows[0].sourceFileSha256='0'.repeat(64)
 assert.throws(()=>check.assess(Buffer.from(JSON.stringify(docket)),legacy),/ORIGINAL_FILE_BYTES_DRIFT/)
 const modified=JSON.parse(original)
 modified.rows[0].originalRevisionSha256='f'.repeat(64)
 assert.throws(()=>check.assess(Buffer.from(JSON.stringify(modified)),legacy),/ORIGINAL_QUESTION_REVISION_DRIFT/)
})
test('source report remains preserved but unsafe v1 generation is explicitly blocked',()=>{
 const legacy=fs.readFileSync(path.join(rooted,'docs/question-bank/ASSPS_GRADE910_PROCESSED_ACADEMIC_CORRECTIONS_20261014.json'))
 const output=check.assess()
 assert.equal(output.legacyProcessedLedgerSha256,SHA(legacy))
 const old=require('../qbank/process-grade910-academic-corrections-20261014.cjs')
 assert.throws(()=>old.processAll(),/UNSAFE_V1_CLAIMS_SUPERSEDED/)
})
test('published v2 audit reproducible and source files were not silently rewritten',()=>{
 const actual=JSON.parse(fs.readFileSync(check.OUT))
 assert.deepEqual(actual,check.assess())
 const summary=fs.readFileSync(check.SUMMARY,'utf8')
 assert.match(summary,/superse(?:des|ding)/i)
 assert.match(summary,/zero|\*\*0\*\*/i)
 assert.match(summary,/never substitute default option A/)
})
