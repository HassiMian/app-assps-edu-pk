'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs')
const big=require('../qbank/prepare-grade910-389-mark-consistent-long-rubrics-20261014.cjs')
const essays=require('../qbank/author-grade910-eight-essay-assessment-drafts-20261014.cjs')
test('all 389 P2 long-answer original SHA-bound marks faithfully preserved',()=>{
 const r=big.generate()
 assert.equal(r.reviewItems,389)
 assert.equal(r.exactQuestionAndFileShaChecked,389)
 assert.deepEqual(r.originalSourceMarkDistribution,{4:38,5:342,7:9})
 assert.equal(r.historicGenericFourMarkTemplateWrongQuestionMarkCount,351)
 assert.equal(r.actualAnswerFactsIndependentlyVerified,0)
 assert.ok(r.rows.every(x=>x.originalAnswerReference&&x.originalStem&&x.originalRevisionSha256))
 assert.ok(r.rows.every(x=>x.proposedTotalRubricMarks===undefined ? x.totalProposedRubricMarks===x.marks : false))
 assert.ok(r.rows.every(x=>x.proposedMarksAwareAssessmentCriteria.reduce((t,c)=>t+c.marks,0)===x.marks))
 assert.ok(r.rows.every(x=>!x.qualifedTeacherReviewed&&!x.qualifiedTeacherReviewed&&!x.academicallyApproved&&!x.published))
})
test('marks mismatch is visible for all 351 legacy mismatched 5/7-mark long answers',()=>{
 const r=big.generate()
 assert.equal(r.rows.filter(x=>x.marks!==4).length,351)
 assert.equal(r.rows.filter(x=>x.marks===4).length,38)
 assert.equal(r.rows.filter(x=>x.marks===5).length,342)
 assert.equal(r.rows.filter(x=>x.marks===7).length,9)
 assert.deepEqual(JSON.parse(fs.readFileSync(big.OUT)),r)
 const report=fs.readFileSync(big.SUMMARY,'utf8')
 assert.match(report,/351\/389/)
 assert.match(report,/38 four-mark/)
 assert.match(report,/342 five-mark/)
 assert.match(report,/9 seven-mark/)
})
test('8 essay rubrics are original-SHA bound, genre-specific and mark-correct for English and Urdu',()=>{
 const r=essays.build()
 assert.equal(r.rows.length,8)
 assert.equal(r.exactOriginalShaValidated,8)
 assert.equal(r.sourceEnglishItems,4)
 assert.equal(r.sourceUrduItems,4)
 assert.ok(r.rows.every(x=>x.originalQuestionMarks===x.proposedTotalMarks))
 assert.deepEqual(r.rows.reduce((o,x)=>(o[x.originalQuestionMarks]=(o[x.originalQuestionMarks]||0)+1,o),{}),{5:4,8:4})
 assert.ok(r.rows.every(x=>x.proposedCriteria.reduce((t,v)=>t+v.marks,0)===x.originalQuestionMarks))
 assert.ok(r.rows.every(x=>x.multipleValidStudentAnswersAllowed&&!x.independentQualifiedTeacherReviewed))
 assert.deepEqual(JSON.parse(fs.readFileSync(essays.OUT)),r)
})
test('English essays distinguish community volunteering, exhibitions, speech and dialogue constraints',()=>{
 const r=new Map(essays.build().rows.map(x=>[x.originalId,x]))
 assert.match(r.get('IX-ENG-ORIG-20261008-W001').proposedCriteria.map(x=>x.topicSpecificCriterion).join(' '),/120–150/)
 assert.match(r.get('IX-ENG-ORIG-20261008-W002').proposedCriteria.map(x=>x.topicSpecificCriterion).join(' '),/counterargument/)
 assert.match(r.get('IX-ENG-ORIG-20261008-W003').proposedCriteria.map(x=>x.topicSpecificCriterion).join(' '),/one minute/)
 assert.match(r.get('IX-ENG-ORIG-20261008-W004').proposedCriteria.map(x=>x.topicSpecificCriterion).join(' '),/8–10/)
})
test('Urdu essay prompts are meaningful Unicode without encoding corruption or fake review signatures',()=>{
 const r=essays.build().rows
 for(const x of r.filter(x=>x.medium==='urdu')){
  const s=x.proposedCriteria.map(v=>v.topicSpecificCriterion).join(' ')
  assert.match(s,/[\u0600-\u06ff]/)
  assert.doesNotMatch(s,/[ØÙÛ]/)
  assert.equal(x.principalSigned,false)
  assert.equal(x.textbookExerciseEvidenceVerified,false)
  assert.equal(x.academicallyApproved,false)
 }
})
test('no generated paper content or school database publication authorized by rubric candidates',()=>{
 const essaysData=essays.build(),longs=big.generate()
 assert.equal(essaysData.approved,0);assert.equal(essaysData.published,0)
 assert.equal(longs.teacherApproved,0);assert.equal(longs.principalApproved,0);assert.equal(longs.published,0)
 assert.ok(longs.rows.every(x=>x.paperStudioSelectable===false))
 assert.ok(essaysData.rows.every(x=>x.paperStudioSelectable===false))
})
