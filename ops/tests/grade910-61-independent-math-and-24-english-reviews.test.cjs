'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),crypto=require('node:crypto')
const numerical=require('../qbank/recompute-grade910-61-numerical-reference-answers-20261014.cjs')
const english=require('../qbank/review-grade910-english9-24-mcq-20261014.cjs')
const sha=x=>crypto.createHash('sha256').update(x).digest('hex')
test('61 original numerical stems are integrity-bound and independently re-evaluated by subject-appropriate formulas',()=>{
 const r=numerical.verify()
 assert.equal(r.rows.length,61)
 assert.equal(r.sourceOriginalRevisionChecksInherited,61)
 assert.equal(r.arithmeticAndSymbolicReferenceAgreements,61)
 assert.equal(r.realQualifiedFacultyReviewCount,0)
 assert.equal(r.academicallyApproved,0)
 assert.equal(r.published,0)
 assert.ok(r.rows.every(x=>x.independentComputationAgreesWithSourceReference))
 assert.ok(r.rows.every(x=>/^[a-f0-9]{64}$/.test(x.originalRevisionSha256)))
 assert.ok(r.rows.every(x=>x.originalStem.length>10 && sha(x.originalStem)===x.originalStemSha256))
 assert.ok(r.rows.every(x=>x.curriculumAndExercisePageCertified===false))
 assert.deepEqual(JSON.parse(fs.readFileSync(numerical.OUTPUT)),r)
})
test('arithmetic, symbolic, physical-unit and geometric formulas have independent reference checks',()=>{
 const calc=numerical.compute
 assert.equal(calc('force',[4,3]).value,12)
 assert.equal(calc('heat',[2,4200,5]).value,42000)
 assert.equal(calc('hyp',[6,8]).value,10)
 assert.equal(calc('factor',[2,3]).representation,'(x+2)(x+3)')
 assert.equal(calc('det',[2,3,1,4]).value,5)
 assert.equal(calc('roots',[2,3]).value[0],2)
 assert.deepEqual(calc('complexMultiply',[2,3,1,-2]).value,[8,-1])
 assert.equal(calc('complexMultiply',[2,3,1,-2]).representation,'8-i')
 assert.equal(calc('refractive',[3e8,2e8]).value,1.5)
 assert.equal(calc('sqrt2',[72]).representation,'6√2')
})
test('wrong reference answers are not rubber-stamped because their statements look like formulas',()=>{
 assert.equal(numerical.matchSourceAnswer('force',[4,3],numerical.compute('force',[4,3]),'F=ma=4×3=13 N'),false)
 assert.equal(numerical.matchSourceAnswer('scientific',[0.00045],numerical.compute('scientific',[0.00045]),'4.5×10⁻⁵'),false)
 assert.equal(numerical.matchSourceAnswer('complexMultiply',[2,3,1,-2],numerical.compute('complexMultiply',[2,3,1,-2]),'9-i'),false)
 assert.equal(numerical.matchSourceAnswer('roots',[2,3],numerical.compute('roots',[2,3]),'x=2 or x=4'),false)
})
test('authored English 9 MCQs receive 24 individually explained model language assessments, never qualified-teacher signatures',()=>{
 const x=english.inspect()
 assert.equal(x.candidateCount,24)
 assert.equal(x.independentLanguageReasoningAgreementCount,24)
 assert.deepEqual(x.selectedKeyCounts,{A:0,B:17,C:7,D:0})
 assert.equal(x.academicallyApproved,0)
 assert.equal(x.qualifiedTeacherApproved,0)
 assert.ok(x.rows.every(r=>r.explanation.length>35))
 assert.ok(x.rows.every(r=>r.schoolTextbookEditionVerified===false))
 assert.ok(x.rows.every(r=>r.independentQualifiedFacultyReviewed===false))
 assert.deepEqual(JSON.parse(fs.readFileSync(english.OUT)),x)
})
test('all original Grade IX–X candidate source data and school release status preserved',()=>{
 const p=JSON.parse(fs.readFileSync(numerical.OUTPUT))
 const e=JSON.parse(fs.readFileSync(english.OUT))
 assert.equal(p.originalSourceFilesRewritten,false)
 assert.equal(p.realQualifiedFacultyReviewCount,0)
 assert.equal(e.published,0)
 assert.ok(p.rows.every(r=>r.originalRevisionSha256&&!r.academicallyApproved&&!r.published))
 assert.ok(e.rows.every(r=>r.originalRevisionSha256&&!r.academicallyApproved&&!r.published))
})
