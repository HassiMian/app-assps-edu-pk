'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),crypto=require('node:crypto')
const plugin=require('../qbank/prepare-grade910-private-faculty-quality-overlay-20261015.cjs')
const sha=b=>crypto.createHash('sha256').update(b).digest('hex')
const meta=JSON.parse(fs.readFileSync(plugin.PUBLIC))
const quality=require('../../docs/question-bank/ASSPS_GRADE910_2581_SOURCE_SHA_ACADEMIC_QUALITY_RISK_TRIAGE_20261015.json')
test('all 2581 source candidates and the 2580 private reviews remain source-hash linked',()=>{
 assert.equal(meta.sourceOriginals,2581)
 assert.equal(meta.privateFacultyQuestions,2580)
 assert.equal(meta.reviewGroups,56)
 assert.equal(meta.heldIncompleteOriginal,'X-CHEM-C23-L01')
 assert.equal(meta.originalRiskDocketSha256,sha(fs.readFileSync(
  require('node:path').join(__dirname,'../../docs/question-bank/ASSPS_GRADE910_2581_SOURCE_SHA_ACADEMIC_QUALITY_RISK_TRIAGE_20261015.json'))))
 assert.equal(quality.metrics.originalMcqCandidates,875)
 assert.equal(quality.metrics.originalLongAnswers,564)
})
test('only public-safe aggregate evidence crosses the repository privacy boundary',()=>{
 assert.equal(typeof meta.privatePrioritySha256,'string')
 assert.match(meta.privatePrioritySha256,/^[a-f0-9]{64}$/)
 assert.equal(Object.hasOwn(meta,'groups'),false)
 assert.equal(Object.hasOwn(meta,'privateDirectory'),false)
 for(const banned of ['originalAnswer','questionText','options','staffSignature','studentId','studentName','reviewerEmail'])
  assert.ok(!Object.hasOwn(meta,banned))
})
test('prioritized research cannot authorize institutional faculty or principal approval',()=>{
 assert.equal(meta.teacherReviewed,0)
 assert.equal(meta.schoolBooksAdoptedAuthenticated,0)
 assert.equal(meta.academicallyApproved,0)
 assert.equal(meta.published,0)
 assert.match(meta.publicationStatus,/HOLD/)
})
test('owner-only offline blind-review start page is checksum bound to the private priority manifest',()=>{
 const renderer=require('../qbank/render-grade910-private-quality-index-20261015.cjs')
 const receipt=JSON.parse(fs.readFileSync(renderer.ATTEST,'utf8'))
 assert.equal(receipt.originalResearchQuestions,2581)
 assert.equal(receipt.blindReviewCandidates,2580)
 assert.equal(receipt.privateReviewGroups,56)
 assert.equal(receipt.privateSourcePrioritySha256,meta.privatePrioritySha256)
 assert.match(receipt.offlineBlindIndexSha256,/^[a-f0-9]{64}$/)
 assert.equal(receipt.reviewedByRealSubjectTeacher,0)
 assert.equal(receipt.academicallyApproved,0)
 assert.equal(receipt.published,0)
})
