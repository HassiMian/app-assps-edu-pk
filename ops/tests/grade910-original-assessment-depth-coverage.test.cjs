'use strict'
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs')
const m=require('../qbank/audit-grade910-original-assessment-depth.cjs')
const stored=()=>JSON.parse(fs.readFileSync(m.OUT,'utf8'))
test('all 2581 original authoring questions grouped exactly into raw 396 grade subject chapter buckets',()=>{
 const x=stored()
 assert.equal(x.originalQuestionCount,2581)
 assert.equal(x.originalSubjectIdCount,26)
 assert.equal(x.authoredGradeSubjectChapterBuckets,396)
 assert.equal(x.rows.length,396)
 assert.equal(x.rows.reduce((s,r)=>s+r.candidates,0),2581)
 assert.equal(new Set(x.rows.map(r=>[r.originalAuthorGradeClaim,
  r.originalAuthorSubjectClaim,r.originalAuthorChapterNumber].join('|'))).size,396)
})
test('grade/subject/medium and type original claims are not magically school-certified',()=>{
 const x=stored()
 assert.deepEqual(x.rawOriginalGradeClaims,{'9':1584,'10':953,UNASSIGNED:44})
 assert.deepEqual(x.rawOriginalMediumClaims,{english:1512,urdu:971,dual:48,UNASSIGNED:50})
 assert.equal(x.originalsMissingFormalCurriculumSubjectId,44)
 assert.equal(x.originalQuestionsMissingGrade,44)
 assert.equal(x.originalQuestionsMissingChapter,44)
 assert.equal(x.originalQuestionsMissingTopic,44)
 assert.equal(x.originalQuestionsMissingMedium,50)
 assert.equal(x.rawOriginalTypeClaims.mcq,875)
 assert.equal(x.rawOriginalTypeClaims.short,908)
 assert.equal(x.rawOriginalTypeClaims.long,564)
 assert.equal(x.rawOriginalTypeClaims.numerical,91)
})
test('source pages, archive recovery and authoring-bucket mix do NOT grant textbook approval',()=>{
 const x=stored()
 assert.equal(x.sourceRecordsClaimingNonNullOriginalPdfPage,1393)
 assert.equal(x.genuinePhysicallyValidatedPrintedExercisePageCount,0)
 assert.equal(x.sourceArchiveRecoveredOriginals,204)
 assert.equal(x.sourceArchiveRecoveredOriginalGrade9,54)
 assert.equal(x.sourceArchiveRecoveredOriginalGrade10,150)
 assert.equal(x.independentFacultyApprovedQuestions,0)
 assert.equal(x.verifiedPublishedQuestions,0)
 assert.equal(x.actualASSPSAdoptedSyllabusChapterCountAuthenticated,0)
 assert.ok(x.rows.every(r=>r.sourceAdoptionBySchoolVerified===false))
 assert.ok(x.rows.every(r=>r.paperStudioAcademicallyVerifiedSelectable===0))
})
test('complete metadata-only assessment depth report deterministic and no original question passages',()=>{
 const x=stored()
 assert.deepEqual(x,m.build())
 assert.equal(fs.readFileSync(m.MD,'utf8'),m.markdown(x))
 assert.equal(x.chapterBucketsHavingMcqButNoShortOrLong,1)
 assert.ok(x.rows.every(r=>!Object.hasOwn(r,'stem')&&!Object.hasOwn(r,'answer')))
 assert.ok(x.rows.every(r=>Object.hasOwn(r,'sourceQuestionTypeSignals')))
})
